import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createClient } from "@supabase/supabase-js";
import fixtures from "../../../tests/browser-fixtures.cjs";
import { provisionAdminAccount, validateAdminAccountInput } from "../../../src/lib/admin-account-creation.mjs";

const { setup, fixture } = fixtures;
const admin = await fixture("ADMIN");
const actor = createClient(process.env.API_URL, process.env.ANON_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
assert.equal((await actor.auth.signInWithPassword(admin)).error, null);
let counter = 0;
function input(roles, managerId = null) {
  const id = randomUUID();
  const result = validateAdminAccountInput({ requestId: id, name: "Created by Admin", email: `${id}@example.test`, phone: "07" + String(Date.now() + counter++).slice(-8), code: `ADMIN_NEW_${id}`, password: "CreatedPassword1", roles, managerId });
  assert.equal(result.ok, true);
  return result.value;
}
const dmRole = "10000000-0000-0000-0000-000000000002";
const saRole = "10000000-0000-0000-0000-000000000004";
const umRole = "10000000-0000-0000-0000-000000000003";
const dmInput = input([dmRole]);
const run = (value, caller = actor, actorId = admin.id) => provisionAdminAccount({ authAdmin: setup.auth.admin, caller, actorId, input: value });
assert.deepEqual(await run(dmInput), { ok: true, accountId: dmInput.requestId });
assert.deepEqual(await run(dmInput), { ok: true, accountId: dmInput.requestId });
const umInput = input([umRole], dmInput.requestId);
assert.equal((await run(umInput)).ok, true);
const saInput = input([saRole], umInput.requestId);
assert.equal((await run(saInput)).ok, true);
const account = await actor.from("tai_khoan").select("trang_thai,manager_id").eq("id", saInput.requestId).single();
assert.equal(account.data.trang_thai, "DANG_HOAT_DONG");
assert.equal(account.data.manager_id, umInput.requestId);
const userClient = createClient(process.env.API_URL, process.env.ANON_KEY, { auth: { persistSession: false } });
assert.equal((await userClient.auth.signInWithPassword({ email: saInput.email, password: saInput.password })).error, null);
const duplicate = { ...input([saRole], dmInput.requestId), phone: saInput.phone };
assert.deepEqual(await run(duplicate), { ok: false, code: "duplicate" });
assert.ok((await setup.auth.admin.getUserById(duplicate.requestId)).error, "failed business transaction must not leave its identity");
const invalidManager = input([saRole], randomUUID());
assert.equal((await run(invalidManager)).ok, false);
assert.ok((await setup.auth.admin.getUserById(invalidManager.requestId)).error);
const denied = await userClient.rpc("admin_create_business_account", { target_auth_user_id: saInput.requestId, full_name: "Forged", account_email: saInput.email, phone_number: saInput.phone, agent_code: saInput.code, direct_manager_id: dmInput.requestId, selected_role_ids: [dmRole] });
assert.equal(denied.error?.code, "42501");
const forgedMarker = await actor.rpc("admin_create_business_account", { target_auth_user_id: admin.id, full_name: "Forged", account_email: admin.email, phone_number: "0912345678", agent_code: "FORGED", direct_manager_id: null, selected_role_ids: [dmRole] });
assert.equal(forgedMarker.error?.code, "42501", "even an Admin cannot adopt an identity without its server-owned creation marker");
const foreignRequest = { ...input([dmRole]), requestId: saInput.requestId, email: saInput.email };
const otherAdmin = await fixture("ADMIN");
const otherCaller = createClient(process.env.API_URL, process.env.ANON_KEY, { auth: { persistSession: false } });
assert.equal((await otherCaller.auth.signInWithPassword(otherAdmin)).error, null);
assert.equal((await run(foreignRequest, otherCaller, otherAdmin.id)).ok, false);
assert.equal((await setup.auth.admin.getUserById(saInput.requestId)).data.user.id, saInput.requestId);
console.log("Admin account creation integration PASS: active DM/SA, password login, idempotent retry, duplicate compensation, invalid manager, non-Admin and cross-actor denial.");
